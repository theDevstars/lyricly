export function iconFor(word: string): string | null {
  const bare = word
    .toLowerCase()
    .replace(/[^\p{L}\p{N}']/gu, '')
    .replace(/'s$/, '');
  if (!bare) return null;
  if (ICONS[bare]) return ICONS[bare];

  for (const [key, icon] of Object.entries(ICONS)) {
    if (bare === key) return icon;
    if (bare.length > 4 && key.length > 4 && (bare.startsWith(key) || key.startsWith(bare))) {
      return icon;
    }
  }
  return null;
}

export function hasIcon(word: string): boolean {
  return iconFor(word) !== null;
}
